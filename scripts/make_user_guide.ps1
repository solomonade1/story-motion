<#
.SYNOPSIS
  Builds packaging\USER_GUIDE.md (the single-file guide shipped inside the zip) from the pages in docs\guide\.
.DESCRIPTION
  The pages in docs\guide\ are the source of truth. This joins them in file-name order, moves every heading down one
  level (so each page title becomes a "##" part), and adds a title and contents list. The pages must not contain
  relative links, because the zip has no repository next to it. Lines that start with "> Screenshot to add:" are
  placeholders and are dropped from the zip guide.
  Run after editing any page:  .\scripts\make_user_guide.ps1
#>
$ErrorActionPreference = "Stop"
$repo = Split-Path -Parent $PSScriptRoot
$pages = Get-ChildItem (Join-Path $repo "docs\guide") -Filter "0*.md" | Sort-Object Name
$out = New-Object System.Collections.Generic.List[string]
$toc = New-Object System.Collections.Generic.List[string]
$body = New-Object System.Collections.Generic.List[string]
foreach ($p in $pages) {
  $text = [IO.File]::ReadAllText($p.FullName)
  if ($text -match "\]\((?!https?://|#)[^)]*\)") { throw "$($p.Name) contains a relative link; the zip guide must be self-contained." }
  $inFence = $false
  foreach ($line in ($text -split "`r?`n")) {
    if ($line -match '^> Screenshot to add:') { continue }   # placeholders for the repository pages only; never shipped in the zip
    if ($line -match '^```') { $inFence = -not $inFence }
    if (-not $inFence -and $line -match '^(#{1,5}) (.*)$') {
      $line = "#$($Matches[1]) $($Matches[2])"
      if ($Matches[1] -eq "#") { $toc.Add("- " + $Matches[2]) }
    }
    $body.Add($line)
  }
  $body.Add("")
}
$out.Add("# StoryMotion Studio: User Guide")
$out.Add("")
$out.Add("This guide comes inside the download. It covers installing, making a video, exporting, keeping your files safe, updating, uninstalling and fixing problems. You do not need any technical knowledge.")
$out.Add("")
$out.Add("**Contents**")
$out.Add("")
$out.AddRange($toc)
$out.Add("")
$out.Add('**Quick start:** extract the zip to a folder such as `C:\Apps`, open the extracted folder, double-click **StoryMotion Studio.vbs**. If anything goes wrong, read the Troubleshooting part.')
$out.Add("")
$out.Add("<!-- Generated by scripts\make_user_guide.ps1 from docs\guide\*.md. Edit those pages, not this file. -->")
$out.Add("")
$out.AddRange($body)
$target = Join-Path $repo "packaging\USER_GUIDE.md"
[IO.File]::WriteAllText($target, (($out -join "`n").TrimEnd() + "`n"), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Wrote $target ($($pages.Count) pages)"
